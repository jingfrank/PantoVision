#!/bin/bash
# ==============================================================================
# gongwang_clean 轻量部署打包脚本 (彻底排除 models/ 大文件)
# 生成的 zip 包仅约 200KB，专供从主程序 Web / 管理平台上传部署使用
# ==============================================================================

set -e

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TIMESTAMP=$(date +%Y%m%d_%H%M%S)
OUTPUT_ZIP="${SRC_DIR}/gongwang_clean_app_${TIMESTAMP}.zip"

echo "======================================================================"
echo "📦 正在打包 gongwang_clean 业务代码（排除 models/ 大模型权重）..."
echo "======================================================================"

cd "${SRC_DIR}"

# 排除 models/、.git/、临时缓存、测试与本地日志
zip -r "${OUTPUT_ZIP}" . \
    -x "models/*" \
    -x ".git/*" \
    -x "local_cache/*" \
    -x "events/*" \
    -x "__pycache__/*" \
    -x "*.pyc" \
    -x ".pytest_cache/*" \
    -x "*.zip"

echo ""
echo "======================================================================"
echo "✅ 打包完成！"
echo "📂 生成文件: ${OUTPUT_ZIP}"
echo "📏 文件大小: $(du -h "${OUTPUT_ZIP}" | cut -f1)"
echo "💡 说明: 该压缩包体积极小（~200KB），上传至主程序秒级完成，绝不超时！"
echo "💡 提示: 目标板宿主机已通过 docker-compose.yml 挂载持久化 models 目录，代码解压后可无缝直接加载模型。"
echo "======================================================================"
